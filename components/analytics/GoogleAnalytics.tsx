import Script from "next/script";

// Only renders once NEXT_PUBLIC_GA_MEASUREMENT_ID is set (Vercel project env
// var) -- keeps analytics out of local/dev/preview builds until a real GA4
// property exists. See CLAUDE.md / deployment notes for setup steps.
export default function GoogleAnalytics() {
  const measurementId = process.env.NEXT_PUBLIC_GA_MEASUREMENT_ID;
  if (!measurementId) return null;

  return (
    <>
      <Script
        src={`https://www.googletagmanager.com/gtag/js?id=${measurementId}`}
        strategy="afterInteractive"
      />
      <Script id="ga4-init" strategy="afterInteractive">
        {`
          window.dataLayer = window.dataLayer || [];
          function gtag(){dataLayer.push(arguments);}
          gtag('js', new Date());
          gtag('config', '${measurementId}');
        `}
      </Script>
    </>
  );
}
